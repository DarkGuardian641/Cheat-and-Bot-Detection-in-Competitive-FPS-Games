def _sanitize_filename(filename: str) -> str:
    """Strip directory traversal elements, slashes, and hazardous characters."""
    base_name = Path(filename).name
    # Remove any characters other than alphanumeric, dots, underscores, dashes
    sanitized = re.sub(r"[^a-zA-Z0-9._-]", "_", base_name)
    return sanitized or "unnamed_match"


def _get_analysis_path(analysis_id: str) -> Path:
    # Analysis IDs are generated by the API; reject unexpected values instead
    # of silently mapping a path-like ID onto another record.
    if not re.fullmatch(r"[A-Za-z0-9_-]+", analysis_id):
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Analysis '{analysis_id}' not found.",
        )
    return settings.ANALYSIS_DIR / f"{analysis_id}.json"


def _read_analysis_data(analysis_id: str) -> dict[str, Any]:
    path = _get_analysis_path(analysis_id)
    if not path.is_file():
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Analysis '{analysis_id}' not found.",
        )
    try:
        with open(path, "r", encoding="utf-8") as f:
            return json.load(f)
    except json.JSONDecodeError as e:
        logger.error("Corrupted JSON in analysis record %s: %s", path, e)
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="Analysis record is corrupted.",
        ) from e
    except OSError as e:
        logger.error("OS error reading analysis file %s: %s", path, e)
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="Failed to load analysis record.",
        ) from e


def _save_analysis_data(analysis_id: str, data: dict[str, Any]) -> None:
    path = _get_analysis_path(analysis_id)
    temporary_path = path.with_suffix(".json.tmp")
    try:
        with open(temporary_path, "w", encoding="utf-8") as f:
            json.dump(data, f, indent=2)
        temporary_path.replace(path)
    finally:
        temporary_path.unlink(missing_ok=True)


def run_demo_pipeline_task(file_path: Path, analysis_id: str) -> None:
    """
    Background worker:
    Executes parsing / feature inference completely outside the HTTP request lifecycle.
    Supports both native .dem replay binary files and .parquet pre-extracted dataset files.
    Updates job status: pending -> processing -> completed / failed.
    """
    logger.info("Background task started: analysis_id=%s, file=%s", analysis_id, file_path.name)
    try:
        current_data = _read_analysis_data(analysis_id)
        current_data["status"] = "processing"
        current_data["updated_at"] = datetime.now(UTC).isoformat()
        _save_analysis_data(analysis_id, current_data)

        if file_path.suffix.lower() == ".parquet":
            report = analyze_parquet_file(
                parquet_path=file_path,
                model_path=settings.DEFAULT_MODEL_PATH,
                config_path=settings.DEFAULT_CONFIG_PATH,
            )
        else:
            # Run demo parsing, feature extraction & ML inference
            report = analyze_demo_file(
                demo_path=file_path,
                model_path=settings.DEFAULT_MODEL_PATH,
                config_path=settings.DEFAULT_CONFIG_PATH,
            )

        # Merge job metadata
        report["analysis_id"] = analysis_id
        report["match_id"] = analysis_id
        report["status"] = "completed"
        report["completed_at"] = datetime.now(UTC).isoformat()
        report["demo_path"] = str(file_path)

        _save_analysis_data(analysis_id, report)
        logger.info("Background task completed successfully: analysis_id=%s", analysis_id)

    except (KeyboardInterrupt, SystemExit):
        raise
    except BaseException as e:
        # demoparser2 surfaces Rust panics as pyo3 PanicException, which derives
        # from BaseException; without this the job would stay "processing" forever.
        logger.exception("Background task failed for analysis %s", analysis_id)
        try:
            failed_record = _read_analysis_data(analysis_id)
        except (HTTPException, OSError):
            failed_record = {"analysis_id": analysis_id, "match_id": analysis_id}

        failed_record["status"] = "failed"
        failed_record["error"] = str(e)
        failed_record["failed_at"] = datetime.now(UTC).isoformat()
        _save_analysis_data(analysis_id, failed_record)


