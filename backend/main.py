@app.post(
    "/api/upload",
    response_model=UploadResponse,
    status_code=status.HTTP_202_ACCEPTED,
    include_in_schema=False,
)
async def upload_demo(
    background_tasks: BackgroundTasks,
    file: Annotated[UploadFile, File(description="Counter-Strike 2 replay file (.dem) or dataset match (.parquet)")],
):
    """
    Upload a CS2 .dem replay file or a .parquet telemetry dataset file for cheat detection analysis.
    Validates file format and size, stores the file locally, and starts asynchronous analysis.
    """
    raw_filename = file.filename or ""
    lower_name = raw_filename.lower()
    is_dem = lower_name.endswith(".dem")
    is_parquet = lower_name.endswith(".parquet")

    if not (is_dem or is_parquet):
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Invalid file format. Only Counter-Strike 2 (.dem) replay files or (.parquet) dataset files are supported.",
        )

    safe_name = _sanitize_filename(raw_filename)
    analysis_id = f"analysis_{uuid.uuid4().hex[:12]}"
    stored_filename = f"{analysis_id}_{safe_name}"
    save_path = settings.DEMOS_DIR / stored_filename

    try:
        with open(save_path, "wb") as buffer:  # noqa: ASYNC230
            shutil.copyfileobj(file.file, buffer)
    except OSError as e:
        logger.error("Failed writing uploaded file to %s: %s", save_path, e)
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="Failed to store uploaded file.",
        ) from e

    # Validate file size & magic bytes for .dem files (or basic check for .parquet)
    if is_dem:
        is_valid, err_msg = validate_demo_file(save_path, max_size_mb=settings.MAX_DEMO_SIZE_MB)
        if not is_valid:
            save_path.unlink(missing_ok=True)
            logger.warning("Demo validation failed for %s: %s", raw_filename, err_msg)
            raise HTTPException(
                status_code=status.HTTP_400_BAD_REQUEST,
                detail=f"Demo validation error: {err_msg}",
            )
    elif is_parquet:
        file_size_mb = save_path.stat().st_size / (1024 * 1024)
        if file_size_mb > settings.MAX_DEMO_SIZE_MB:
            save_path.unlink(missing_ok=True)
            raise HTTPException(
                status_code=status.HTTP_400_BAD_REQUEST,
                detail=f"File exceeds maximum allowed size of {settings.MAX_DEMO_SIZE_MB}MB.",
            )

    # Persist pending record
    initial_record = {
        "analysis_id": analysis_id,
        "match_id": analysis_id,
        "status": "pending",
        "filename": safe_name,
        "saved_path": str(save_path),
        "created_at": datetime.now(UTC).isoformat(),
        "total_windows": 0,
        "suspicious_players": [],
    }
    _save_analysis_data(analysis_id, initial_record)

    # Launch background processing
    background_tasks.add_task(run_demo_pipeline_task, save_path, analysis_id)

    return {
        "analysis_id": analysis_id,
        "match_id": analysis_id,
        "status": "pending",
        "filename": safe_name,
        "message": f"{'Demo' if is_dem else 'Parquet dataset'} uploaded and validated successfully. Background processing initiated.",
    }


@app.get(
    "/analyses",
    response_model=list[AnalysisListItem],
    tags=["Analyses"],
)
def list_analyses():
    """List all previous analysis jobs with their processing status."""
    analyses: list[dict[str, Any]] = []
    for report_file in settings.ANALYSIS_DIR.glob("*.json"):
        try:
            with open(report_file, "r", encoding="utf-8") as f:
                data = json.load(f)
            analyses.append({
                "analysis_id": data.get("analysis_id", report_file.stem),
                "filename": data.get("match_info", {}).get("demo_filename") or data.get("filename", "unknown"),
                "status": data.get("status", "unknown"),
                "created_at": data.get("created_at"),
                "completed_at": data.get("completed_at"),
                "total_windows": data.get("total_windows", 0),
                "suspicious_players_count": len(data.get("suspicious_players", [])),
                "error": data.get("error"),
            })
        except (json.JSONDecodeError, OSError, UnicodeDecodeError) as e:
            logger.warning("Failed reading analysis file %s: %s", report_file, e)

    analyses.sort(key=lambda x: str(x.get("created_at", "") or x.get("completed_at", "")), reverse=True)
    return analyses


