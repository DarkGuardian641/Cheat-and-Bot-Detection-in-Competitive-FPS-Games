@app.get(
    "/players",
    response_model=list[PlayerListItem],
    tags=["Players"],
)
def list_players():
    """Aggregate and list all tracked players across all analyzed match replays."""
    player_map: dict[str, dict[str, Any]] = {}

    for report_file in settings.ANALYSIS_DIR.glob("*.json"):
        try:
            with open(report_file, "r", encoding="utf-8") as f:
                data = json.load(f)

            if data.get("status") != "completed":
                continue

            completed_at = data.get("completed_at")
            summaries = data.get("player_summaries", {})
            for steamid, p_summary in summaries.items():
                if steamid not in player_map:
                    player_map[steamid] = {
                        "player_id": steamid,
                        "player_name": p_summary.get("player_name", "Unknown"),
                        "matches_analyzed": 0,
                        "total_windows": 0,
                        "suspicious_windows": 0,
                        "overall_suspicious_ratio": 0.0,
                        "overall_verdict": "Clean",
                        "last_seen": completed_at,
                    }
                entry = player_map[steamid]
                entry["matches_analyzed"] += 1
                entry["total_windows"] += p_summary.get("total_windows", 0)
                entry["suspicious_windows"] += p_summary.get("suspicious_windows", 0)
                if completed_at and (not entry["last_seen"] or completed_at > entry["last_seen"]):
                    entry["last_seen"] = completed_at
                # Update player name if previous was Unknown
                if entry["player_name"] == "Unknown" and p_summary.get("player_name"):
                    entry["player_name"] = p_summary.get("player_name")
        except (json.JSONDecodeError, OSError, UnicodeDecodeError, KeyError) as e:
            logger.warning("Error reading report %s for player aggregation: %s", report_file, e)

    # Compute final ratios and verdicts
    results = []
    for steamid, entry in player_map.items():
        total_w = entry["total_windows"]
        sus_w = entry["suspicious_windows"]
        ratio = round(sus_w / total_w, 4) if total_w > 0 else 0.0
        entry["overall_suspicious_ratio"] = ratio
        entry["overall_verdict"] = "Flagged" if ratio >= 0.15 or sus_w >= 5 else "Clean"
        results.append(entry)

    # Sort suspects first, then by match count descending
    results.sort(key=lambda x: (x["overall_verdict"] == "Flagged", x["overall_suspicious_ratio"], x["matches_analyzed"]), reverse=True)
    return results


@app.get(
    "/players/{player_id}",
    response_model=PlayerDetailResponse,
    responses={404: {"model": ErrorResponse}},
    tags=["Players"],
)
def get_player_details(player_id: str):
    """Retrieve historical analysis metrics and suspicion flags for a specific player across all matches."""
    player_matches = []
    total_evaluated_windows = 0
    total_suspicious_windows = 0
    player_name = "Unknown"

    for report_file in settings.ANALYSIS_DIR.glob("*.json"):
        try:
            with open(report_file, "r", encoding="utf-8") as f:
                data = json.load(f)

            if data.get("status") != "completed":
                continue

            summaries = data.get("player_summaries", {})
            if player_id in summaries:
                p_summary = summaries[player_id]
                player_name = p_summary.get("player_name", player_name)
                total_evaluated_windows += p_summary.get("total_windows", 0)
                total_suspicious_windows += p_summary.get("suspicious_windows", 0)

                player_matches.append({
                    "match_id": data.get("analysis_id", report_file.stem),
                    "demo_filename": data.get("match_info", {}).get("demo_filename", "unknown"),
                    "total_windows": p_summary.get("total_windows", 0),
                    "suspicious_windows": p_summary.get("suspicious_windows", 0),
                    "suspicious_ratio": p_summary.get("suspicious_ratio", 0.0),
                    "mean_suspicion_score": p_summary.get("mean_suspicion_score", 0.0),
                    "max_suspicion_score": p_summary.get("max_suspicion_score", 0.0),
                    "verdict": p_summary.get("status", "Clean"),
                })
        except (json.JSONDecodeError, OSError, UnicodeDecodeError, KeyError) as e:
            logger.warning("Error reading report %s for player %s: %s", report_file, player_id, e)

    if not player_matches:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Player with ID '{player_id}' not found in any processed matches.",
        )

    overall_suspicious_ratio = (
        round(total_suspicious_windows / total_evaluated_windows, 4)
        if total_evaluated_windows > 0 else 0.0
    )

    return {
        "player_id": player_id,
        "player_name": player_name,
        "matches_analyzed": len(player_matches),
        "total_windows": total_evaluated_windows,
        "suspicious_windows": total_suspicious_windows,
        "overall_suspicious_ratio": overall_suspicious_ratio,
        "overall_verdict": "Flagged" if overall_suspicious_ratio >= 0.15 else "Clean",
        "matches": player_matches,
    }
